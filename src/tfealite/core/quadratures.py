import numpy as np


class GeneralizedDuffy:
    def __init__(self, _x_e):
        pass

    def transform(self, u, v, beta):
        u_d = u**beta
        v_d = v
        j_d = beta * u ** (2 * beta - 1)
        xi_ddt = u_d * (1 - v_d)
        eta_ddt = u_d * v_d
        return np.asarray([xi_ddt, eta_ddt, j_d])


class DuffyDistance:
    def __init__(self, x_e):
        r21 = x_e[0] - x_e[1]
        r23 = x_e[2] - x_e[1]
        self.vp = np.dot(r21, r23) / np.dot(r23, r23)
        r2p = r23 * self.vp
        # self.vp = np.linalg.norm(r2p) / np.linalg.norm(r23)
        r1p = x_e[1] + r2p - x_e[0]
        self.d = np.linalg.norm(r1p) / np.linalg.norm(r23)
        self.s_min = np.log(np.sqrt(self.vp**2 + self.d**2) - self.vp)
        self.s_max = np.log(np.sqrt((1 - self.vp) ** 2 + self.d**2) + (1 - self.vp))

    def transform(self, u, v, beta):
        u_ddt = u**beta
        s = self.s_min + v * (self.s_max - self.s_min)
        v_ddt = (np.exp(s) - self.d**2 * np.exp(-s)) / 2 + self.vp
        j_ddt = (
            beta
            * u ** (2 * beta - 1)
            * np.sqrt((v_ddt - self.vp) ** 2 + self.d**2)
            * (self.s_max - self.s_min)
        )
        xi_ddt = u_ddt * (1 - v_ddt)
        eta_ddt = u_ddt * v_ddt
        return np.asarray([xi_ddt, eta_ddt, j_ddt])


class DuffySinh3D:
    def __init__(self, x_e):
        """
        if vertex singularity node 1 is singular point
        if edge singularity edge 1-2 is singular line

        Args:
            x_e: np.ndarray, physical node coords
        """
        r13 = x_e[2] - x_e[0]
        r12 = x_e[1] - x_e[0]
        r34 = x_e[3] - x_e[2]
        # Project on plane perpendicular to 1-2
        r1p3 = r13 - np.dot(r12, r13) / np.dot(r12, r12) * r12
        rp3p4 = r34 - np.dot(r12, r34) / np.dot(r12, r12) * r12
        self.vp = -np.dot(r1p3, rp3p4) / np.dot(rp3p4, rp3p4)
        r1p = r1p3 + self.vp * rp3p4
        self.d = np.linalg.norm(r1p) / np.linalg.norm(rp3p4)
        self.s_min = np.arcsinh(-self.vp / self.d)
        self.s_max = np.arcsinh((1 - self.vp) / self.d)

    def transform(self, nat_coords, beta1, beta2):
        """
        vertex singularity 1 / r^alpha:
            alpha = 1 => beta1 = 1, beta2 = 1
            alpha = 1/2 => beta1 = 2, beta2 = 1

        edge singularity 1 / r^alpha:
            alpha = 1 => beta1 = 1, beta2 = 1
            alpha = 1/2 => beta1 = 2, beta2 = 2


        Args:
            nat_coords: np.ndarray, natural coordinates for unit hex
            beta1: int, exponent along u direction
            beta2: int, exponent along v direction
        """
        u = nat_coords[0, :]
        v = nat_coords[1, :]
        w = nat_coords[2, :]
        u_sinh = u**beta1
        v_sinh = v**beta2
        s = self.s_min + w * (self.s_max - self.s_min)
        w_sinh = self.vp + self.d * np.sinh(s)

        j_sinh = (
            beta1
            * beta2
            * u ** (3 * beta1 - 1)
            * v ** (2 * beta2 - 1)
            * np.cosh(s)
            * self.d
            * (self.s_max - self.s_min)
        )

        xi = u_sinh * (1 - v_sinh)
        eta = u_sinh * v_sinh * (1 - w_sinh)
        zeta = u_sinh * v_sinh * w_sinh
        return np.vstack([xi, eta, zeta, j_sinh])


class DuffySinh:
    def __init__(self, x_e):
        r21 = x_e[0] - x_e[1]
        r23 = x_e[2] - x_e[1]
        self.vp = np.dot(r21, r23) / np.dot(r23, r23)
        r2p = r23 * self.vp
        # self.vp = np.linalg.norm(r2p) / np.linalg.norm(r23)
        r1p = x_e[1] + r2p - x_e[0]
        self.d = np.linalg.norm(r1p) / np.linalg.norm(r23)
        self.s_min = np.arcsinh(-self.vp / self.d)
        self.s_max = np.arcsinh((1 - self.vp) / self.d)

    def transform(self, u, v, beta):
        u_sinh = u**beta
        s = self.s_min + v * (self.s_max - self.s_min)
        v_sinh = self.vp + self.d * np.sinh(s)
        # j_sinh = self.d * np.cosh(s) * (self.s_max - self.s_min)
        j_sinh = (
            beta * u ** (2 * beta - 1) * self.d * np.cosh(s) * (self.s_max - self.s_min)
        )

        xi = u_sinh * (1 - v_sinh)
        eta = u_sinh * v_sinh
        return np.asarray([xi, eta, j_sinh])


def generate_bar_rules(max_order):
    rules = {}
    for order in range(1, max_order + 1):
        xi, weights = np.polynomial.legendre.leggauss(order)
        rule_matrix = np.column_stack((xi, weights))
        rules[order] = (rule_matrix, 1.0)
    return rules


def generate_quad_rule(points_per_dim, unit_quad=False):
    x_1d, w_1d = np.polynomial.legendre.leggauss(points_per_dim)

    if unit_quad:
        x_1d = 0.5 * (x_1d + 1.0)
        w_1d = 0.5 * w_1d

    X, Y = np.meshgrid(x_1d, x_1d)
    WX, WY = np.meshgrid(w_1d, w_1d)

    points_2d = np.vstack([X.ravel(), Y.ravel(), (WX * WY).ravel()]).T

    return points_2d, 1.0


def generate_hex_rule(points_per_dim, unit_hex=True):
    x_1d, w_1d = np.polynomial.legendre.leggauss(points_per_dim)

    if unit_hex:
        x_1d = 0.5 * (x_1d + 1.0)
        w_1d = 0.5 * w_1d

    X, Y, Z = np.meshgrid(x_1d, x_1d, x_1d, indexing="ij")
    WX, WY, WZ = np.meshgrid(w_1d, w_1d, w_1d, indexing="ij")

    points_3d = np.vstack([X.ravel(), Y.ravel(), Z.ravel(), (WX * WY * WZ).ravel()]).T

    return points_3d, 1.0


