# convert quadrature rule from https://people.math.sc.edu/Burkardt/c_src/tetrahedron_arbq_rule/tetrahedron_arbq_rule.c
# to one usable for unit tetrahedron

import numpy as np


def convert_xg_to_unit(xs, ys, zs, ws):
    """
    Converts Xiao-Gimbutas quadrature points from a symmetric reference
    tetrahedron to the standard unit tetrahedron [(0,0,0), (1,0,0), (0,1,0), (0,0,1)].
    """
    # 1. Define Burkardt Reference Tetrahedron Vertices (Equilateral)
    s3 = np.sqrt(3.0)
    s6 = np.sqrt(6.0)

    # 1. Define the Vertices you provided
    # v1 = (-1, -1/s3, -1/s6)
    # v2 = ( 0,  2/s3, -1/s6)
    # v3 = ( 1, -1/s3, -1/s6)
    # v4 = ( 0,  0,    3/s6)
    v = np.array(
        [
            [-1.0, 0.0, 1.0, 0.0],  # X
            [-1.0 / s3, 2.0 / s3, -1.0 / s3, 0.0],  # Y
            [-1.0 / s6, -1.0 / s6, -1.0 / s6, 3.0 / s6],  # Z
            [1.0, 1.0, 1.0, 1.0],  # Barycentric constraint
        ]
    )
    # Pre-invert the vertex matrix for efficiency
    v_inv = np.linalg.inv(v)

    points_unit = []
    weights_unit = []

    # 2. Volume scale factor
    # V_ref = 8*sqrt(3)/27, V_unit = 1/6
    # If weights sum to 1 (normalized), factor is 1/6.
    # If weights sum to V_ref, factor is (1/6) / V_ref.
    original_sum = np.sum(ws)
    vol_ref = (8.0 * np.sqrt(3.0)) / 27.0

    # Check if rule is normalized (sum=1) or physical (sum=vol)
    is_normalized = np.isclose(original_sum, 1.0, atol=1e-5)
    weight_scale = (1.0 / 6.0) if is_normalized else (1.0 / 6.0) / vol_ref

    for i in range(len(xs)):
        # Solve for barycentric coordinates: v * lambda = p
        p_ref = np.array([xs[i], ys[i], zs[i], 1.0])
        lambdas = v_inv @ p_ref

        # Unit coordinates are simply (lambda_2, lambda_3, lambda_4)
        # because V1 maps to (0,0,0)
        points_unit.append(lambdas[1:4])
        weights_unit.append(ws[i] * weight_scale)

    return np.array(points_unit), np.array(weights_unit)


